import { INSTALL_MARKER_SCHEMA } from './install-marker-schema.mjs';

const hexPattern = (length) => `^[${INSTALL_MARKER_SCHEMA.hexCharacters}]{${length}}$`;

export function renderJqSourceMarkerValidator() {
  const s = INSTALL_MARKER_SCHEMA;
  const backslash = JSON.stringify('\\');
  const uncPrefix = JSON.stringify('\\\\');
  return `# Generated by packages/myco/scripts/gen-release-selector.mjs from install-marker-schema.mjs.
        def exact($pattern): . as $v | [match($pattern)] | length == 1 and .[0].offset == 0 and .[0].length == ($v | length);
        def components_valid: length > 0 and all(. != "" and . != "." and . != "..");
        def canonical_checkout:
          . as $p |
          if ($p | startswith("/")) then ($p | split("/") | .[1:] | components_valid)
          elif ($p | startswith(${uncPrefix})) then
            (($p | contains("/") | not) and ($p | split(${backslash}) | .[2:] | length >= 3)
             and ($p | split(${backslash}) | .[2:] | components_valid))
          else
            (($p | length >= 4) and ($p[0:1] | test("^[A-Za-z]$")) and $p[1:3] == (":" + ${backslash})
             and ($p | contains("/") | not) and ($p[3:] | split(${backslash}) | components_valid))
          end;
        def source_checkout_valid:
          .source != "${s.source}" or
          ((.channel as $c | [${s.channels.map(channel => `"${channel}"`).join(', ')}] | index($c) != null)
           and (.checkout | type == "string") and (.checkout | canonical_checkout)
           and (.commit | type == "string") and (.commit | exact("${hexPattern(s.commitLength)}"))
           and (.version | type == "string") and (.version | exact("${s.versionPattern}"))
           and (.binary_sha256 | type == "string") and (.binary_sha256 | exact("${hexPattern(s.binaryHashLength)}"))
           and ((has("prerelease") | not) or (.prerelease | type == "boolean"))
           and (.bin | type == "string") and (.bin | startswith("/")));
`;
}

export function renderAwkSourceMarkerValidator() {
  const s = INSTALL_MARKER_SCHEMA;
  return `# Generated by packages/myco/scripts/gen-release-selector.mjs from install-marker-schema.mjs.
      if (mode=="marker" && marker_source=="${s.source}") {
        checkout_path=marker_checkout
        backslash=sprintf("%c",92)
        if (substr(checkout_path,1,1)=="/") {
          checkout_path=substr(checkout_path,2)
          checkout_parts=split(checkout_path,checkout_part,"/")
        } else if (substr(checkout_path,1,2)==backslash backslash) {
          if (index(checkout_path,"/")) exit 1
          checkout_path=substr(checkout_path,3)
          gsub(/\\\\/,"/",checkout_path)
          checkout_parts=split(checkout_path,checkout_part,"/")
          if (checkout_parts<3) exit 1
        } else if (substr(checkout_path,1,1)~/^[A-Za-z]$/ && substr(checkout_path,2,2)==":" backslash) {
          if (index(checkout_path,"/")) exit 1
          checkout_path=substr(checkout_path,4)
          gsub(/\\\\/,"/",checkout_path)
          checkout_parts=split(checkout_path,checkout_part,"/")
        } else exit 1
        if (checkout_parts<1) exit 1
        for (checkout_index=1;checkout_index<=checkout_parts;checkout_index++)
          if (checkout_part[checkout_index]=="" || checkout_part[checkout_index]=="." || checkout_part[checkout_index]=="..") exit 1
        if (marker_channel !~ /^(${s.channels.join('|')})$/ ||
            length(marker_commit)!=${s.commitLength} || marker_commit ~ /[^${s.hexCharacters}]/ ||
            marker_version !~ /${s.versionPattern}/ ||
            length(marker_hash)!=${s.binaryHashLength} || marker_hash ~ /[^${s.hexCharacters}]/ ||
            (marker_prerelease!="" && marker_prerelease!~/^(true|false)$/) || marker_bin !~ /^\\//) exit 1
      }
`;
}

export function renderPowerShellSourceMarkerValidator() {
  const s = INSTALL_MARKER_SCHEMA;
  return `# Generated by packages/myco/scripts/gen-release-selector.mjs from install-marker-schema.mjs.
function Test-CanonicalCheckoutPath {
    param($Value)
    if ($Value -isnot [string]) { return $false }
    if ($Value.StartsWith('/')) {
        $parts = $Value.Substring(1).Split([char]'/')
    } elseif ($Value.StartsWith('\\\\')) {
        if ($Value.Contains('/')) { return $false }
        $parts = $Value.Substring(2).Split([char]'\\')
        if ($parts.Count -lt 3) { return $false }
    } elseif ($Value -cmatch '^[A-Za-z]:\\\\') {
        if ($Value.Contains('/')) { return $false }
        $parts = $Value.Substring(3).Split([char]'\\')
    } else { return $false }
    foreach ($part in $parts) {
        if ($part -ceq '' -or $part -ceq '.' -or $part -ceq '..') { return $false }
    }
    return $true
}
if (-not $ChannelExplicit -and $InstallMarker -and $InstallMarker.source -eq '${s.source}') {
    $checkout = $InstallMarker.checkout
    if ($InstallMarker.channel -cnotin @(${s.channels.map(channel => `'${channel}'`).join(', ')}) -or
        -not (Test-CanonicalCheckoutPath $checkout) -or
        -not ($InstallMarker.commit -is [string]) -or $InstallMarker.commit -cnotmatch '^[${s.hexCharacters}]{${s.commitLength}}\\z' -or
        -not ($InstallMarker.version -is [string]) -or $InstallMarker.version -cnotmatch '${s.versionPattern.replace(/\$$/, '\\z')}' -or
        -not ($InstallMarker.binary_sha256 -is [string]) -or $InstallMarker.binary_sha256 -cnotmatch '^[${s.hexCharacters}]{${s.binaryHashLength}}\\z' -or
        ($InstallMarker.PSObject.Properties.Name -contains 'prerelease' -and -not ($InstallMarker.prerelease -is [bool])) -or
        -not ($InstallMarker.bin -is [string]) -or -not [System.IO.Path]::IsPathRooted($InstallMarker.bin)) {
        throw "Invalid source checkout install marker at $Marker. Pass -Channel stable, beta, or alpha (or set MYCO_CHANNEL) to choose a release explicitly, or repair the marker."
    }
}
`;
}
