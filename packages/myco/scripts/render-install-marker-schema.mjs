import { SOURCE_MARKER_SCHEMA } from './install-marker-schema.mjs';

const hexPattern = (length) => `^[${SOURCE_MARKER_SCHEMA.hexCharacters}]{${length}}$`;

export function renderJqSourceMarkerValidator() {
  const s = SOURCE_MARKER_SCHEMA;
  return `# Generated by packages/myco/scripts/gen-release-selector.mjs from install-marker-schema.mjs.
        def exact($pattern): . as $v | [match($pattern)] | length == 1 and .[0].offset == 0 and .[0].length == ($v | length);
        def source_checkout_valid:
          .source != "${s.source}" or
          ((.channel as $c | [${s.channels.map(channel => `"${channel}"`).join(', ')}] | index($c) != null)
           and (.checkout | type == "string") and (.checkout | startswith("/"))
           and (.checkout | split("/") | .[1:] | all(. != "" and . != "." and . != ".."))
           and (.commit | type == "string") and (.commit | exact("${hexPattern(s.commitLength)}"))
           and (.version | type == "string") and (.version | exact("${s.versionPattern}"))
           and (.binary_sha256 | type == "string") and (.binary_sha256 | exact("${hexPattern(s.binaryHashLength)}"))
           and ((has("prerelease") | not) or (.prerelease | type == "boolean"))
           and (.bin | type == "string") and (.bin | startswith("/")));
`;
}

export function renderAwkSourceMarkerValidator() {
  const s = SOURCE_MARKER_SCHEMA;
  return `# Generated by packages/myco/scripts/gen-release-selector.mjs from install-marker-schema.mjs.
      if (mode=="marker" && marker_source=="${s.source}") {
        if (marker_channel !~ /^(${s.channels.join('|')})$/ ||
            marker_checkout !~ /^\\// || marker_checkout=="/" || marker_checkout ~ /\\/\\// || marker_checkout ~ /\\/$/ || marker_checkout ~ /\\/\\.\\.?($|\\/)/ ||
            length(marker_commit)!=${s.commitLength} || marker_commit ~ /[^${s.hexCharacters}]/ ||
            marker_version !~ /${s.versionPattern}/ ||
            length(marker_hash)!=${s.binaryHashLength} || marker_hash ~ /[^${s.hexCharacters}]/ ||
            (marker_prerelease!="" && marker_prerelease!~/^(true|false)$/) || marker_bin !~ /^\\//) exit 1
      }
`;
}

export function renderPowerShellSourceMarkerValidator() {
  const s = SOURCE_MARKER_SCHEMA;
  return `# Generated by packages/myco/scripts/gen-release-selector.mjs from install-marker-schema.mjs.
if ($InstallMarker -and $InstallMarker.source -eq '${s.source}') {
    $checkout = $InstallMarker.checkout
    if ($InstallMarker.channel -cnotin @(${s.channels.map(channel => `'${channel}'`).join(', ')}) -or
        -not ($checkout -is [string]) -or -not [System.IO.Path]::IsPathRooted($checkout) -or
        [System.IO.Path]::GetFullPath($checkout) -cne $checkout -or
        [System.IO.Path]::GetPathRoot($checkout) -ceq $checkout -or
        -not ($InstallMarker.commit -is [string]) -or $InstallMarker.commit -cnotmatch '^[${s.hexCharacters}]{${s.commitLength}}\\z' -or
        -not ($InstallMarker.version -is [string]) -or $InstallMarker.version -cnotmatch '${s.versionPattern.replace(/\$$/, '\\z')}' -or
        -not ($InstallMarker.binary_sha256 -is [string]) -or $InstallMarker.binary_sha256 -cnotmatch '^[${s.hexCharacters}]{${s.binaryHashLength}}\\z' -or
        ($InstallMarker.PSObject.Properties.Name -contains 'prerelease' -and -not ($InstallMarker.prerelease -is [bool])) -or
        -not ($InstallMarker.bin -is [string]) -or -not [System.IO.Path]::IsPathRooted($InstallMarker.bin)) {
        throw "Invalid source checkout install marker at $Marker."
    }
}
`;
}
