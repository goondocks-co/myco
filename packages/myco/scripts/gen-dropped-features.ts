import { readFileSync, writeFileSync } from 'node:fs';

/** DROP decisions shipped with the server, projected from the canonical Myco ledger. */
export function renderDroppedFeatures(ledger: string): string {
  let section: string | null = null;
  const rows: { section: string; row: string }[] = [];
  for (const line of ledger.split('\n')) {
    const heading = /^### (7\.\d+)\b/.exec(line);
    if (heading) { section = heading[1]!; continue; }
    if (/^## /.test(line)) { section = null; continue; }
    if (section !== null && line.startsWith('| `') && line.split('|')[2]?.trim() === 'DROP') rows.push({ section, row: line });
  }
  if (rows.length === 0) throw new Error('The architecture ledger contains no DROP decisions.');
  return '// AUTO-GENERATED by scripts/gen-dropped-features.ts — DO NOT EDIT.\n'
    + 'export const DROPPED_FEATURES = ' + JSON.stringify(rows, null, 2) + ' as const;\n';
}

if (process.argv[1]?.endsWith('gen-dropped-features.ts')) {
  writeFileSync(new URL('../../myco-server/src/core/dropped-features.generated.ts', import.meta.url),
    renderDroppedFeatures(readFileSync(new URL('../../../docs/architecture/myco-2.0.md', import.meta.url), 'utf8')));
}
