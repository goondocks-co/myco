/**
 * Runners: the Deployment's own execution identities, and the one module that issues, rotates, revokes and
 * controls them.
 *
 * A runner is not a member. Its bearer authenticates against `runner_credentials` alone, its authority is the
 * current `credential_epoch` of a runner row that is not removed, and nothing here reads a member role except the
 * owner or administrator who registers or controls one. Every bearer is generated by the runner's own client and
 * reaches this Deployment once, as the digest it stores: registration binds the candidate the client sent with its
 * device request, and a rotation binds the successor the client staged before asking.
 *
 * - Registration commits at the dashboard approval: one guarded batch creates the runner, binds the candidate as its
 *   first credential, records the audit and decides the device request, while the approver is a live owner or
 *   administrator. A poll mints nothing.
 * - Rotation follows the member cadence (seven-day credentials, the last quarter as the refresh window, a 90-day
 *   idle bound) with a separate lineage. Asking twice with the same candidate answers the same successor. A
 *   successor's first use moves the runner's live lease attribution to it and revokes its predecessor; presenting
 *   that predecessor to the rotation route afterwards ends every credential of the runner.
 * - Pause stops new claims and keeps everything else. Removal tombstones the runner and moves its epoch, which ends
 *   every credential and every run token minted under it at once.
 */
