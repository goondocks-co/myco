import type { RelationalStore } from '../core/adapters.js';
import { SCHEMA_STEPS, type SchemaStep } from './schema.js';

/** The file name a step is emitted under; migration files are applied in name order and each is recorded once. */
export function migrationFileName(step: SchemaStep): string {
  return `${String(step.version).padStart(4, '0')}_v${step.version}.sql`;
}

/** One step as an executable SQL file; the version stamp is its last statement. */
export function renderMigrationFile(step: SchemaStep): string {
  return `-- Generated by npm run migrations:emit from src/db/schema.ts (schema step ${step.version}); do not edit.\n\n${step.statements.map((s) => `${s};`).join('\n\n')}\n`;
}

/** Every step as `{ name, sql }`, in application order. */
export function renderMigrationFiles(): { name: string; sql: string }[] {
  return SCHEMA_STEPS.map((step) => ({ name: migrationFileName(step), sql: renderMigrationFile(step) }));
}

/** The stamped schema version of a database, or 0 when the meta table or the row is absent. */
export async function readSchemaVersion(db: RelationalStore): Promise<number> {
  try {
    const row = await db.prepare(`SELECT value FROM schema_meta WHERE key = 'version'`).first<{ value: string }>();
    return row ? Number(row.value) : 0;
  } catch (err) {
    if (err instanceof Error && /no such table/i.test(err.message)) return 0;
    throw err;
  }
}
