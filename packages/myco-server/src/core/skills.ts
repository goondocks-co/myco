export async function recordSkillUsage(
  db: RelationalStore, scope: ReadScope, row: { id: string; skillId: string; sessionId: string; detectedAt: number },
): Promise<void> {
  await db.batch([
    db.prepare(`INSERT INTO skill_usage (project_id, id, skill_id, session_id, detected_at) VALUES (?, ?, ?, ?, ?)`)
      .bind(scope.projectId, row.id, row.skillId, row.sessionId, row.detectedAt),
    db.prepare(`UPDATE skill_records SET usage_count = usage_count + 1, last_used_at = ?
       WHERE project_id = ? AND id = ?`).bind(row.detectedAt, scope.projectId, row.skillId),
  ]);
}
