/**
 * The skill lifecycle, server-side: candidates, records, lineage and usage.
 *
 * Four properties the 1.4 vault encodes that a translation drops:
 *
 * **Lineage is the source of truth for a skill's content.** `skill_records`
 * carries metadata and a path; the on-disk SKILL.md is a materialization. The
 * published content is the latest lineage snapshot, ordered by generation.
 *
 * **`approved_at` stamps on the FIRST transition into approved and never
 * moves.** 1.4 reads the row, decides, then writes, which is safe only where
 * nothing yields between. Here it is one conditional expression, so two callers
 * approving at once cannot both stamp and the second cannot overwrite the first.
 *
 * **Deleting a skill dismisses the candidates that point at it.** A candidate
 * left approved and still naming a deleted skill is regenerated by the next
 * survey, which is how a deliberately removed skill comes back.
 *
 * **A candidate update may not move a candidate between Projects.** The
 * settable columns are a fixed list, as with a run update: `project_id`, `id`
 * and `agent_id` are absent from it.
 */
import type { RelationalStore } from './adapters.js';
import type { ReadScope } from '../read/scope.js';

export const SKILL_STATUSES = ['active', 'archived', 'superseded'] as const;
export const CANDIDATE_STATUSES = ['identified', 'approved', 'dismissed', 'generated'] as const;

/**
 * The columns a candidate update may set.
 *
 * `approved_at` is absent: it is stamped by the transition rather than written
 * by a caller, which is what makes it a single audit trail rather than a field
 * anyone may rewrite.
 */
export const CANDIDATE_UPDATE_COLUMNS = [
  'topic', 'rationale', 'confidence', 'status', 'source_ids', 'skill_id', 'supersedes',
  'evidence_bundle_id', 'quality_score', 'quality_failures', 'coverage_matches',
  'last_reconciled_at', 'reconciliation_reason',
] as const;
export type CandidateUpdateColumn = (typeof CANDIDATE_UPDATE_COLUMNS)[number];
export type CandidateUpdate = Partial<Record<CandidateUpdateColumn, string | number | null>>;

/** Columns a candidate update may never set. */
export const CANDIDATE_IMMUTABLE_COLUMNS = ['project_id', 'id', 'agent_id', 'approved_at'] as const;

const RECORD_COLUMNS = `id, agent_id AS agentId, name, display_name AS displayName, description,
  status, embedded, generation, candidate_id AS candidateId, source_ids AS sourceIds, path,
  usage_count AS usageCount, last_used_at AS lastUsedAt, created_at AS createdAt,
  updated_at AS updatedAt, properties`;

const CANDIDATE_COLUMNS = `id, agent_id AS agentId, topic, rationale, confidence, status,
  source_ids AS sourceIds, skill_id AS skillId, supersedes, evidence_bundle_id AS evidenceBundleId,
  quality_score AS qualityScore, quality_failures AS qualityFailures, coverage_matches AS coverageMatches,
  last_reconciled_at AS lastReconciledAt, reconciliation_reason AS reconciliationReason,
  created_at AS createdAt, updated_at AS updatedAt, approved_at AS approvedAt`;

export interface SkillRecordInsert {
  id: string; agentId: string; name: string; displayName: string; description: string;
  status?: string; generation?: number; candidateId: string | null; sourceIds: string;
  path: string; createdAt: number; properties?: string;
}

export interface CandidateInsert {
  id: string; agentId: string; topic: string; rationale: string; confidence: number;
  status?: string; sourceIds: string; createdAt: number;
}

export interface LineageInsert {
  id: string; skillId: string; generation: number; action: string; rationale: string;
  sourceIdsAdded: string; contentSnapshot: string; createdAt: number;
}

