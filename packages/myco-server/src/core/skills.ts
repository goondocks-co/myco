export async function insertLineage(db: RelationalStore, scope: ReadScope, row: LineageInsert): Promise<void> {
  await db.prepare(`INSERT INTO skill_lineage
      (project_id, id, skill_id, generation, action, rationale, source_ids_added, content_snapshot, created_at)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`)
    .bind(scope.projectId, row.id, row.skillId, row.generation, row.action, row.rationale,
      row.sourceIdsAdded, row.contentSnapshot, row.createdAt).run();
}

export async function listLineageForSkill(db: RelationalStore, scope: ReadScope, skillId: string, limit = 50): Promise<unknown[]> {
  const { results } = await db
    .prepare(`SELECT id, skill_id AS skillId, generation, action, rationale,
        source_ids_added AS sourceIdsAdded, content_snapshot AS contentSnapshot, created_at AS createdAt
      FROM skill_lineage WHERE project_id = ? AND skill_id = ?
      ORDER BY generation DESC, created_at DESC, id DESC LIMIT ?`)
    .bind(scope.projectId, skillId, Math.min(limit, 200)).all();
  return results;
}

/**
 * The canonical published content: the latest lineage snapshot.
 *
 * 1.4 reads this UNSCOPED: its lineage `project_id` is denormalized routing
 * metadata a legacy backfill can leave NULL, and a project filter there could
 * only hide a skill's own history. Server-side the column is NOT NULL, which
 * removes that hazard, and the read is scoped like every other.
 */
export async function getPublishedSkillContent(db: RelationalStore, scope: ReadScope, skillId: string): Promise<string | null> {
  const row = await db.prepare(`SELECT content_snapshot AS content FROM skill_lineage
     WHERE project_id = ? AND skill_id = ?
     ORDER BY generation DESC, created_at DESC, id DESC LIMIT 1`)
    .bind(scope.projectId, skillId).first<{ content: string | null }>();
  return row?.content ? row.content : null;
}

/** The snapshot a specific generation recorded, which a pinned reader asks for rather than the latest. */
export async function getSkillContentAtGeneration(
  db: RelationalStore, scope: ReadScope, skillId: string, generation: number,
): Promise<string | null> {
  const row = await db.prepare(`SELECT content_snapshot AS content FROM skill_lineage
     WHERE project_id = ? AND skill_id = ? AND generation = ?
     ORDER BY created_at DESC, id DESC LIMIT 1`)
    .bind(scope.projectId, skillId, generation).first<{ content: string | null }>();
  return row?.content ? row.content : null;
}

