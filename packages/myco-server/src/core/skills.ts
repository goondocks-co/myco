export async function insertSkillRecord(db: RelationalStore, scope: ReadScope, row: SkillRecordInsert): Promise<unknown> {
  return db.prepare(`INSERT INTO skill_records
      (project_id, id, agent_id, name, display_name, description, status, embedded, generation,
       candidate_id, source_ids, path, usage_count, created_at, updated_at, properties)
      VALUES (?, ?, ?, ?, ?, ?, ?, 0, ?, ?, ?, ?, 0, ?, ?, ?)
      RETURNING ${RECORD_COLUMNS}`)
    .bind(scope.projectId, row.id, row.agentId, row.name, row.displayName, row.description,
      row.status ?? 'active', row.generation ?? 1, row.candidateId, row.sourceIds, row.path,
      row.createdAt, row.createdAt, row.properties ?? '{}')
    .first();
}

/** By id, or by name — a name is unique within a Project, which the schema enforces. */
export async function getSkillRecord(db: RelationalStore, scope: ReadScope, idOrName: string): Promise<Record<string, unknown> | null> {
  return db.prepare(`SELECT ${RECORD_COLUMNS} FROM skill_records
     WHERE project_id = ? AND (id = ? OR name = ?) ORDER BY CASE WHEN id = ? THEN 0 ELSE 1 END LIMIT 1`)
    .bind(scope.projectId, idOrName, idOrName, idOrName).first();
}

export async function listSkillRecords(db: RelationalStore, scope: ReadScope, o: { status?: string; limit?: number } = {}): Promise<unknown[]> {
  const conditions = ['project_id = ?'];
  const params: unknown[] = [scope.projectId];
  if (o.status !== undefined) { conditions.push('status = ?'); params.push(o.status); }
  const { results } = await db
    .prepare(`SELECT ${RECORD_COLUMNS} FROM skill_records WHERE ${conditions.join(' AND ')} ORDER BY name ASC LIMIT ?`)
    .bind(...params, Math.min(o.limit ?? 100, 500)).all();
  return results;
}

/** One statement: a read-then-write would lose a concurrent increment. */
export async function incrementSkillUsage(db: RelationalStore, scope: ReadScope, skillId: string, now: number): Promise<void> {
  await db.prepare(`UPDATE skill_records SET usage_count = usage_count + 1, last_used_at = ?
     WHERE project_id = ? AND id = ?`).bind(now, scope.projectId, skillId).run();
}

/**
 * Remove a skill and everything that would resurrect it.
 *
 * Candidates naming this skill are dismissed and their `skill_id` cleared —
 * a candidate left approved and still pointing at a deleted skill is
 * regenerated by the next survey, which is how a deliberately removed skill
 * comes back. One batch, so the record cannot outlive its lineage or the
 * dismissal.
 */
export async function deleteSkillRecordCascade(
  db: RelationalStore, scope: ReadScope, skillId: string, now: number,
): Promise<boolean> {
  const results = await db.batch([
    db.prepare(`DELETE FROM skill_lineage WHERE project_id = ? AND skill_id = ?`).bind(scope.projectId, skillId),
    db.prepare(`DELETE FROM skill_usage WHERE project_id = ? AND skill_id = ?`).bind(scope.projectId, skillId),
    db.prepare(`UPDATE skill_candidates SET status = 'dismissed', skill_id = NULL, updated_at = ?
       WHERE project_id = ? AND (skill_id = ? OR id = (SELECT candidate_id FROM skill_records WHERE project_id = ? AND id = ?))`)
      .bind(now, scope.projectId, skillId, scope.projectId, skillId),
    db.prepare(`DELETE FROM skill_records WHERE project_id = ? AND id = ?`).bind(scope.projectId, skillId),
  ]);
  return results[3].meta.changes > 0;
}

